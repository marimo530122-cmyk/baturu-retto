/* =========================================================
   💎 プレミアム課金の設定（Stripe決済リンク）
   ---------------------------------------------------------
   ここに、あなた自身のStripe決済リンクを貼り付けると
   プレミアム機能の販売が始まります。
   作り方は 要件定義書.md の「プレミアム課金の設定方法」を参照してください。

   ⚠️ 忘れずに：Stripe側の決済リンク設定で「支払い後」を
   「別のウェブサイトに移動させる」にし、移動先URLを
     https://marimo530122-cmyk.github.io/baturu-retto/?paid=1&session_id={CHECKOUT_SESSION_ID}
   にしてください（{CHECKOUT_SESSION_ID} の部分はそのまま入力すればOK。
   Stripeが決済ごとに自動で本物のセッションIDに置き換えてくれます）。

   まだ設定していない間は、アップグレードボタンを押すと
   「設定が必要です」という案内が表示されるだけで、
   それ以外の機能（無料版・開発確認用の ?premium=1 ）には
   一切影響しません。
   ========================================================= */

