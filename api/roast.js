function buildSystemPrompt(characterId, userName) {
  const persona = CHARACTER_PERSONAS[characterId] || CHARACTER_PERSONAS.tagosaku;
  const nameNote = userName
    ? `\n\n相手の名前は「${userName}」です。「お前」「後輩」等の代わりに、できるだけこの名前で呼びかけてください。`
    : "";
  return persona + nameNote + SHARED_RULES;
}

const MAX_MESSAGE_LENGTH = 200;
const MAX_HISTORY_TURNS = 6; // 直近6往復まで（トークン節約・暴走防止）
const MAX_TOKENS = 300;

// Groq APIを1回呼び出す。戻り値: { ok: true, content } / { ok: false, status, detail }
// content は空文字になることがある（呼び出し側で空返答の再送を判断するため、ここではプレースホルダーに変換しない）
async function requestGroqReply(apiKey, systemPrompt, history, message) {
  const response = await fetch("https://api.groq.com/openai/v1/chat/completions", {
    method: "POST",
    headers: {
      "content-type": "application/json",
      authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      model: MODEL,
      messages: [{ role: "system", content: systemPrompt }, ...history, { role: "user", content: message }],
      max_tokens: MAX_TOKENS,
    }),
  });

  if (!response.ok) {
    const errText = await response.text();
    return { ok: false, status: response.status, detail: errText.slice(0, 300) };
  }

  const data = await response.json();
  const content = (data.choices && data.choices[0] && data.choices[0].message && data.choices[0].message.content || "").trim();
  return { ok: true, content };
}

module.exports = async (req, res) => {
  // CORS: GitHub Pages側（静的サイト本体）からのfetchを許可する
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  // ⚠️ 一時的な診断コード（2026-08-22: GROQ_API_KEYが反映されない問題の調査用。原因判明後に削除すること）
  // ブラウザで直接開いて確認できるよう、POSTメソッド限定チェックより前に置く（GETでも許可する）
  if (req.query && (req.query.debug === "1" || req.query.debug === "true")) {
    const groqApiKey = process.env.GROQ_API_KEY;
    const debugInfo = {
      hasGroqKey: typeof groqApiKey === "string" && groqApiKey.length > 0,
      keyLength: (groqApiKey || "").length,
      envKeysContainingGroq: Object.keys(process.env).filter((k) => k.toUpperCase().indexOf("GROQ") !== -1),
      vercelEnv: process.env.VERCEL_ENV || null,
      model: MODEL,
    };

    // キーがあれば、実際にGroq APIへ最小のテスト送信をして、本当のエラー内容まで確認する
    if (debugInfo.hasGroqKey) {
      try {
        const testRes = await fetch("https://api.groq.com/openai/v1/chat/completions", {
          method: "POST",
          headers: {
            "content-type": "application/json",
            authorization: `Bearer ${groqApiKey}`,
          },
          body: JSON.stringify({
            model: MODEL,
            messages: [{ role: "user", content: "こんにちは" }],
            max_tokens: 10,
          }),
        });
        debugInfo.groqTestStatus = testRes.status;
        if (testRes.ok) {
          debugInfo.groqTestOk = true;
        } else {
          debugInfo.groqTestError = (await testRes.text()).slice(0, 500);
        }
      } catch (e) {
        debugInfo.groqTestException = String((e && e.message) || e);
      }
    }

    res.status(200).json(debugInfo);
    return;
  }

  if (req.method === "OPTIONS") {
    res.status(204).end();
    return;
  }
  if (req.method !== "POST") {
    res.status(405).json({ error: "POST only" });
    return;
  }

  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) {
    res.status(500).json({ error: "GROQ_API_KEY is not configured on the server" });
    return;
  }

  let body = req.body;
  if (typeof body === "string") {
    try { body = JSON.parse(body); } catch (e) { body = {}; }
  }
  body = body || {};

  const message = typeof body.message === "string" ? body.message.slice(0, MAX_MESSAGE_LENGTH).trim() : "";
  if (!message) {
    res.status(400).json({ error: "message is required" });
    return;
  }

  const characterId = typeof body.character === "string" ? body.character : "";
  const userName = typeof body.name === "string" ? body.name.slice(0, 20).trim() : "";
  const systemPrompt = buildSystemPrompt(characterId, userName);

  const historyIn = Array.isArray(body.history) ? body.history : [];
  // Groq(OpenAI互換)のロール名はuser/assistantそのままでよい
  const history = historyIn
    .filter((m) => m && (m.role === "user" || m.role === "assistant") && typeof m.content === "string")
    .slice(-MAX_HISTORY_TURNS)
    .map((m) => ({ role: m.role, content: m.content.slice(0, MAX_MESSAGE_LENGTH) }));

  try {
    let result = await requestGroqReply(apiKey, systemPrompt, history, message);
    if (!result.ok) {
      res.status(502).json({ error: "AI provider error", detail: result.detail });
      return;
    }
    // 稀にAIが空の返答を返すことがある（渋さん等、無口なキャラで発生しやすい）ため、
    // その場合はプレースホルダーを出す前に1回だけ同じ内容で再送してみる
    if (!result.content) {
      const retry = await requestGroqReply(apiKey, systemPrompt, history, message);
      if (retry.ok && retry.content) result = retry;
    }
    res.status(200).json({ reply: result.content || "……（絶句している様子）" });
  } catch (e) {
    res.status(500).json({ error: "internal error" });
  }
};
